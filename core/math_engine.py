"""Deterministic clinical math engine — the arithmetic interceptor.

MANDATE (locked): clinical calculations must NEVER be generated by the LLM.
Medical models hallucinate exact numbers. The local harness intercepts
math-intent queries via regex/AST-style parsing, computes them here with
deterministic Python, and re-injects the verified output into the
conversation as ground truth the model is instructed NOT to recompute.

Covered formulas (v1):
  * Cockcroft-Gault creatinine clearance (mL/min)
  * CKD-EPI 2021 race-free eGFR (mL/min/1.73 m², KDIGO staging)
  * Mosteller body surface area (m²)
  * Pediatric mg/kg dosing with optional per-dose cap
  * IV drip rate (gtt/min) and mcg/kg/min infusion rate (mL/hr)
  * Holliday-Segar 4-2-1 maintenance fluids (mL/hr)
  * Anion gap; glucose-corrected sodium

Every result carries: echoed inputs, formula name, citation, warnings,
and interpretation. Unit conversion (lb→kg, in→cm) is explicit.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple


class MathError(ValueError):
    """Raised on out-of-domain inputs — surfaces as a UI error chip."""


# --------------------------------------------------------------- result ----
@dataclass
class MathResult:
    value: float
    unit: str
    formula: str
    inputs: Dict[str, str]
    reference: str
    interpretation: str = ""
    warnings: List[str] = field(default_factory=list)

    def as_context_block(self) -> str:
        """Ground-truth block injected into the model context (and UI chip)."""
        lines = [
            "[DETERMINISTIC MATH — engine-verified. DO NOT recompute, contradict, or round further.]",
            f"Formula: {self.formula}",
            "Inputs:  " + "; ".join(f"{k}={v}" for k, v in self.inputs.items()),
            f"Result:  {self.value:.2f} {self.unit}",
        ]
        if self.interpretation:
            lines.append(f"Context: {self.interpretation}")
        for w in self.warnings:
            lines.append(f"Caution: {w}")
        lines.append(f"Reference: {self.reference}")
        return "\n".join(lines)


# ------------------------------------------------------------ conversions --
LB_PER_KG = 0.45359237
IN_PER_CM = 2.54


def to_kg(weight: float, unit: str) -> float:
    unit = unit.lower().strip(".")
    if unit in ("kg", "kilogram", "kilograms"):
        return weight
    if unit in ("lb", "lbs", "pound", "pounds"):
        return weight * LB_PER_KG
    raise MathError(f"Unknown weight unit '{unit}' — use kg or lb.")


def to_cm(height: float, unit: str) -> float:
    unit = unit.lower().strip(".")
    if unit in ("cm", "centimeter", "centimeters"):
        return height
    if unit in ("m", "meter", "meters"):
        return height * 100.0
    if unit in ("in", "inch", "inches"):
        return height * IN_PER_CM
    raise MathError(f"Unknown height unit '{unit}' — use cm, m, or in.")


# ------------------------------------------------------------- validators --
def _num(name: str, value: float, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        raise MathError(f"{name} must be a number (got {value!r}).")
    if not (lo <= v <= hi):
        raise MathError(f"{name}={v} outside plausible range [{lo}, {hi}] — check the chart.")
    return v


def _sex(value: str) -> str:
    v = (value or "").strip().lower()
    if v in ("m", "male", "man", "boy"):
        return "male"
    if v in ("f", "female", "woman", "girl"):
        return "female"
    raise MathError("sex must be male or female.")


# --------------------------------------------------------------- formulas --
def cockcroft_gault(age_y: float, weight: float, scr_mg_dl: float, sex: str,
                    weight_unit: str = "kg") -> MathResult:
    """CrCl (mL/min). Cockcroft & Gault, Nephron 1976; female ×0.85."""
    a = _num("age", age_y, 0.04, 120)          # accepts neonates via months callers
    w = _num("weight_kg", to_kg(_num("weight", weight, 0.3, 400), weight_unit), 0.3, 400)
    s = _num("serum_creatinine", scr_mg_dl, 0.1, 25.0)
    sx = _sex(sex)
    crcl = ((140.0 - a) * w) / (72.0 * s)
    if sx == "female":
        crcl *= 0.85
    warnings: List[str] = []
    if w > 120:
        warnings.append("Cockcroft-Gault overestimates CrCl in obesity — consider adjusted or lean body weight per protocol.")
    if s < 0.6:
        warnings.append("Very low SCr reduces precision (e.g., sarcopenia) — interpret with caution.")
    interp = "Normal renal function range (≥90 mL/min)." if crcl >= 90 else (
        "Mildly decreased (60–89)." if crcl >= 60 else (
            "Moderately decreased (30–59)." if crcl >= 30 else (
                "Severely decreased (15–29)." if crcl >= 15 else "Kidney failure range (<15) — urgent renal dosing review.")))
    return MathResult(
        value=round(crcl, 2), unit="mL/min", formula="Cockcroft-Gault creatinine clearance",
        inputs={"age": f"{a:g} y", "sex": sx, "weight": f"{w:g} kg", "SCr": f"{s:g} mg/dL"},
        reference="Cockcroft & Gault, Nephron 1976;12:310.",
        interpretation=interp, warnings=warnings,
    )


def ckd_epi_2021(age_y: float, scr_mg_dl: float, sex: str) -> MathResult:
    """Race-free CKD-EPI 2021 eGFR (mL/min/1.73 m²). NKFKDIGO 2021."""
    a = _num("age", age_y, 18, 120)
    s = _num("serum_creatinine", scr_mg_dl, 0.1, 25.0)
    sx = _sex(sex)
    kappa = 0.7 if sx == "female" else 0.9
    alpha = -0.241 if sx == "female" else -0.302
    ratio = s / kappa
    egfr = (
        142.0
        * min(ratio, 1.0) ** alpha
        * max(ratio, 1.0) ** (-1.200)
        * (0.9938 ** a)
        * (1.012 if sx == "female" else 1.0)
    )
    interp = "G1 (≥90) — normal or high." if egfr >= 90 else (
        "G2 (60–89) — mildly decreased." if egfr >= 60 else (
            "G3a (45–59)." if egfr >= 45 else (
                "G3b (30–44)." if egfr >= 30 else (
                    "G4 (15–29) — severe." if egfr >= 15 else "G5 (<15) — kidney failure."))))
    return MathResult(
        value=round(egfr, 1), unit="mL/min/1.73m²", formula="CKD-EPI 2021 (race-free) eGFR",
        inputs={"age": f"{a:g} y", "sex": sx, "SCr": f"{s:g} mg/dL"},
        reference="Inker et al., NEJM 2021;385:1737. KDIGO 2021.",
        interpretation=interp,
        warnings=[] if a >= 18 else ["Validated for adults ≥18 y."],
    )


def bsa_mosteller(height: float, weight: float, height_unit: str = "cm",
                  weight_unit: str = "kg") -> MathResult:
    """BSA (m²) — Mosteller: √(ht_cm × wt_kg / 3600). NEJM 1987."""
    h = _num("height_cm", to_cm(_num("height", height, 30, 260), height_unit), 30, 260)
    w = _num("weight_kg", to_kg(_num("weight", weight, 0.3, 400), weight_unit), 0.3, 400)
    bsa = math.sqrt(h * w / 3600.0)
    return MathResult(
        value=round(bsa, 2), unit="m²", formula="Body surface area — Mosteller",
        inputs={"height": f"{h:g} cm", "weight": f"{w:g} kg"},
        reference="Mosteller RD, NEJM 1987;317:1098.",
        interpretation="Used for carboplatin Calvert dosing, cardiac indices, and burn resuscitation.",
        warnings=[] if bsa < 3.0 else ["Extreme BSA — verify against a second formula (Du Bois) per protocol."],
    )


def pediatric_mgkg_dose(weight: float, mg_per_kg: float, weight_unit: str = "kg",
                        max_single_mg: Optional[float] = None) -> MathResult:
    """Weight-based single dose (mg) with optional hard cap."""
    w = _num("weight_kg", to_kg(_num("weight", weight, 0.3, 200), weight_unit), 0.3, 200)
    r = _num("mg_per_kg", mg_per_kg, 0.001, 200.0)
    dose = w * r
    warnings = ["Pediatric dosing is double-checked against the institutional formulary before administration."]
    capped = False
    if max_single_mg is not None:
        cap = _num("max_single_mg", max_single_mg, 0.01, 10000.0)
        if dose > cap:
            dose, capped = cap, True
            warnings.append(f"Dose capped at formulary maximum {cap:g} mg.")
    return MathResult(
        value=round(dose, 2), unit="mg/dose", formula="Pediatric weight-based dose (mg/kg)",
        inputs={"weight": f"{w:g} kg", "rate": f"{r:g} mg/kg", "capped": "yes" if capped else "no"},
        reference="Institutional pediatric formulary conventions.",
        warnings=warnings,
    )


def iv_drip_rate(volume_ml: float, minutes: float, drop_factor_gtt_ml: float) -> MathResult:
    """Gravity drip rate (gtt/min): (volume × drop factor) / time."""
    v = _num("volume_ml", volume_ml, 0.5, 5000.0)
    t = _num("time_min", minutes, 1.0, 2880.0)
    d = _num("drop_factor", drop_factor_gtt_ml, 10.0, 60.0)
    gtt = v * d / t
    return MathResult(
        value=round(gtt), unit="gtt/min", formula="IV drip rate (gtt/min)",
        inputs={"volume": f"{v:g} mL", "time": f"{t:g} min", "drop factor": f"{d:g} gtt/mL"},
        reference="Standard gravity infusion arithmetic.",
        interpretation="Rounded to whole drops — macro/microdrip set must match the stated drop factor.",
    )


def infusion_rate_mcgkgmin(dose_mcg_kg_min: float, weight: float,
                           concentration_mcg_ml: float, weight_unit: str = "kg") -> MathResult:
    """Pump rate (mL/hr) from mcg/kg/min: dose × weight × 60 / concentration."""
    r = _num("dose", dose_mcg_kg_min, 0.001, 200.0)
    w = _num("weight_kg", to_kg(_num("weight", weight, 0.3, 400), weight_unit), 0.3, 400)
    c = _num("concentration", concentration_mcg_ml, 1.0, 20000.0)
    rate = r * w * 60.0 / c
    return MathResult(
        value=round(rate, 1), unit="mL/hr", formula="Infusion rate from mcg/kg/min",
        inputs={"dose": f"{r:g} mcg/kg/min", "weight": f"{w:g} kg", "concentration": f"{c:g} mcg/mL"},
        reference="Standard continuous infusion arithmetic.",
        interpretation="Verify the bag concentration label before programming the pump.",
    )


def maintenance_fluids_421(weight: float, weight_unit: str = "kg") -> MathResult:
    """Holliday-Segar 4-2-1 maintenance rate (mL/hr)."""
    w = _num("weight_kg", to_kg(_num("weight", weight, 0.3, 200), weight_unit), 0.3, 200)
    rate = 0.0
    if w <= 10:
        rate = 4.0 * w
    elif w <= 20:
        rate = 40.0 + 2.0 * (w - 10.0)
    else:
        rate = 40.0 + 20.0 + 1.0 * (w - 20.0)
    return MathResult(
        value=round(rate, 1), unit="mL/hr", formula="Holliday-Segar 4-2-1 maintenance fluids",
        inputs={"weight": f"{w:g} kg"},
        reference="Holliday & Segar, Pediatrics 1957;19:823.",
        interpretation="First 10 kg ×4, next 10 kg ×2, each kg above 20 ×1.",
        warnings=["Reassess in renal failure, SIADH, or cardiac disease — hypotonic maintenance fluids carry hyponatremia risk."],
    )


def anion_gap(na: float, cl: float, hco3: float) -> MathResult:
    na_ = _num("Na", na, 90, 190)
    cl_ = _num("Cl", cl, 60, 150)
    h_ = _num("HCO3", hco3, 2, 60)
    ag = na_ - (cl_ + h_)
    return MathResult(
        value=round(ag, 1), unit="mEq/L", formula="Anion gap (Na − [Cl + HCO3])",
        inputs={"Na": f"{na_:g}", "Cl": f"{cl_:g}", "HCO3": f"{h_:g}"},
        reference="Emmett & Narins, Arch Intern Med 1977.",
        interpretation="Normal 8–12 (±4). Elevated → consider MUDPILES; low → consider hypoalbuminemia (subtract 2.5 per 1 g/dL albumin below 4).",
    )


def corrected_sodium(na: float, glucose_mg_dl: float) -> MathResult:
    na_ = _num("Na", na, 90, 190)
    g = _num("glucose", glucose_mg_dl, 20, 2000.0)
    corr = na_ + 1.6 * ((g - 100.0) / 100.0)
    warnings = []
    if g > 400:
        warnings.append("At severe hyperglycemia, factor 2.4 may fit better than 1.6 (Hillier, Am J Med 1999).")
    return MathResult(
        value=round(corr, 1), unit="mEq/L", formula="Glucose-corrected sodium",
        inputs={"Na": f"{na_:g}", "glucose": f"{g:g} mg/dL"},
        reference="Katz, NEJM 1973;289:843 (factor 1.6).",
        warnings=warnings,
    )


# ----------------------------------------------------- intent interception --
_RE_AGE = re.compile(r"(\d{1,3}(?:\.\d)?)\s*(?:-?\s*(?:years?|yrs?|yo|y/o|y\.o)|y\b)", re.I)
_RE_WT = re.compile(r"(\d{1,3}(?:\.\d+)?)\s*(kg|kilos?|kilograms?|lbs?|pounds?)\b", re.I)
_RE_HT = re.compile(r"(\d{2,3}(?:\.\d+)?)\s*(cm|centimeters?|m\b|in\b|inches?)", re.I)
_RE_SCR = re.compile(r"(?:s\.?c\.?r\.?|serum creatinine|creatinine)\s*(?:of|=|:|is)?\s*(\d\.\d{1,2})", re.I)
_RE_SEX = re.compile(r"\b(male|man|boy|female|woman|girl|m|f)\b", re.I)
_RE_NUM = re.compile(r"(\d+(?:\.\d+)?)")


def _extract(text: str) -> Dict[str, str]:
    slots: Dict[str, str] = {}
    if m := _RE_AGE.search(text):
        slots["age"] = m.group(1)
    if m := _RE_WT.search(text):
        slots["weight"], slots["weight_unit"] = m.group(1), m.group(2)
    if m := _RE_HT.search(text):
        slots["height"], slots["height_unit"] = m.group(1), m.group(2)
    if m := _RE_SCR.search(text):
        slots["scr"] = m.group(1)
    if m := _RE_SEX.search(text):
        slots["sex"] = m.group(1)
    return slots


INTENT_PATTERNS: List[Tuple[str, re.Pattern, str]] = [
    ("creatinine_clearance", re.compile(r"creatinine clearance|crcl|cockcroft", re.I), "cg"),
    ("egfr", re.compile(r"\begfr\b|gfr\b|ckd-?epi", re.I), "egfr"),
    ("bsa", re.compile(r"\bbsa\b|body surface area", re.I), "bsa"),
    ("peds_dose", re.compile(r"\bmg/kg\b|mg per kg|weight[- ]based dose|pediatric dose|paediatric dose", re.I), "peds"),
    ("drip_rate", re.compile(r"drip rate|gtts?/min|drops? per minute|drop factor", re.I), "drip"),
    ("infusion_rate", re.compile(r"mcg/kg/min|infusion rate|pump rate", re.I), "infusion"),
    ("maintenance_fluids", re.compile(r"maintenance fluids|4[- ]2[- ]1|holliday", re.I), "421"),
    ("anion_gap", re.compile(r"anion gap", re.I), "ag"),
    ("corrected_na", re.compile(r"corrected sodium|correct the sodium|sodium correction", re.I), "na_corr"),
]


def detect_intent(text: str) -> Optional[str]:
    """Return the intercepted formula key, or None if no math intent."""
    for _key, pattern, action in INTENT_PATTERNS:
        if pattern.search(text):
            return action
    return None


def try_compute(text: str) -> Optional[MathResult]:
    """Interceptor entry point: parse slots from free text and compute.

    Returns None when no clinical-math intent is present. Raises MathError
    when intent exists but inputs are missing/invalid — the caller surfaces
    that as an explicit ask rather than letting the LLM improvise numbers.
    """
    action = detect_intent(text)
    if action is None:
        return None
    slots = _extract(text)
    need_err = MathError("Clinical math detected but inputs are incomplete — the LLM is forbidden from guessing numbers. Provide: " + {
        "cg": "age, sex, weight, SCr", "egfr": "age, sex, SCr", "bsa": "height, weight",
        "peds": "weight and mg/kg (plus optional max mg)", "drip": "volume, time, drop factor",
        "infusion": "dose mcg/kg/min, weight, concentration", "421": "weight",
        "ag": "Na, Cl, HCO3", "na_corr": "Na, glucose",
    }[action])
    try:
        if action == "cg":
            if not all(k in slots for k in ("age", "weight", "scr", "sex")):
                raise need_err
            return cockcroft_gault(float(slots["age"]), float(slots["weight"]),
                                   float(slots["scr"]), slots["sex"],
                                   slots.get("weight_unit", "kg"))
        if action == "egfr":
            if not all(k in slots for k in ("age", "scr", "sex")):
                raise need_err
            return ckd_epi_2021(float(slots["age"]), float(slots["scr"]), slots["sex"])
        if action == "bsa":
            if not all(k in slots for k in ("height", "weight")):
                raise need_err
            return bsa_mosteller(float(slots["height"]), float(slots["weight"]),
                                 slots.get("height_unit", "cm"), slots.get("weight_unit", "kg"))
        if action == "peds":
            if "weight" not in slots:
                raise need_err
            m = re.search(r"(\d+(?:\.\d+)?)\s*(?:mg/kg|mg per kg)", text, re.I)
            if not m:
                raise need_err
            cap = re.search(r"max(?:imum)?(?:\s*(?:of|=|:))?\s*(\d+(?:\.\d+)?)\s*mg", text, re.I)
            return pediatric_mgkg_dose(float(slots["weight"]), float(m.group(1)),
                                       slots.get("weight_unit", "kg"),
                                       float(cap.group(1)) if cap else None)
        if action == "drip":
            nums = _RE_NUM.findall(text)
            if len(nums) < 3:
                raise need_err
            return iv_drip_rate(float(nums[0]), float(nums[1]), float(nums[2]))
        if action == "infusion":
            m = re.search(r"(\d+(?:\.\d+)?)\s*mcg/kg/min", text, re.I)
            conc = re.search(r"(\d+(?:\.\d+)?)\s*(?:mcg|mug)/m[lL]", text, re.I)
            if not (m and "weight" in slots and conc):
                raise need_err
            return infusion_rate_mcgkgmin(float(m.group(1)), float(slots["weight"]),
                                          float(conc.group(1)), slots.get("weight_unit", "kg"))
        if action == "421":
            if "weight" not in slots:
                raise need_err
            return maintenance_fluids_421(float(slots["weight"]), slots.get("weight_unit", "kg"))
        if action == "ag":
            nums = _RE_NUM.findall(text)
            if len(nums) < 3:
                raise need_err
            return anion_gap(float(nums[0]), float(nums[1]), float(nums[2]))
        if action == "na_corr":
            nums = _RE_NUM.findall(text)
            if len(nums) < 2:
                raise need_err
            return corrected_sodium(float(nums[0]), float(nums[1]))
    except MathError:
        raise
    raise need_err
