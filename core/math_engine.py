from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple


class MathError(ValueError):
    """Raised on out-of-domain inputs — surfaces as a UI error chip."""


# --------------------------------------------------------------- result ----
@dataclass
class MathResult:
    value: float
    unit: str
    formula: str
    inputs: Dict[str, str]
    reference: str
    interpretation: str = ""
    warnings: List[str] = field(default_factory=list)

    def as_context_block(self) -> str:
        """Ground-truth block injected into the model context (and UI chip)."""
        lines = [
            "[DETERMINISTIC MATH — engine-verified. DO NOT recompute, contradict, or round further.]",
            f"Formula: {self.formula}",
            "Inputs:  " + "; ".join(f"{k}={v}" for k, v in self.inputs.items()),
            f"Result:  {self.value:.2f} {self.unit}",
        ]
        if self.interpretation:
            lines.append(f"Context: {self.interpretation}")
        for w in self.warnings:
            lines.append(f"Caution: {w}")
        lines.append(f"Reference: {self.reference}")
        return "\n".join(lines)


# ------------------------------------------------------------ conversions --
LB_PER_KG = 0.45359237
IN_PER_CM = 2.54


def to_kg(weight: float, unit: str) -> float:
    unit = unit.lower().strip(".")
    if unit in ("kg", "kilogram", "kilograms"):
        return weight
    if unit in ("lb", "lbs", "pound", "pounds"):
        return weight * LB_PER_KG
    raise MathError(f"Unknown weight unit '{unit}' — use kg or lb.")


def to_cm(height: float, unit: str) -> float:
    unit = unit.lower().strip(".")
    if unit in ("cm", "centimeter", "centimeters"):
        return height
    if unit in ("m", "meter", "meters"):
        return height * 100.0
    if unit in ("in", "inch", "inches"):
        return height * IN_PER_CM
    raise MathError(f"Unknown height unit '{unit}' — use cm, m, or in.")


# ------------------------------------------------------------- validators --
def _num(name: str, value: float, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        raise MathError(f"{name} must be a number (got {value!r}).")
    if not (lo <= v <= hi):
        raise MathError(f"{name}={v} outside plausible range [{lo}, {hi}] — check the chart.")
    return v


def _sex(value: str) -> str:
    v = (value or "").strip().lower()
    if v in ("m", "male", "man", "boy"):
        return "male"
    if v in ("f", "female", "woman", "girl"):
        return "female"
    raise MathError("sex must be male or female.")


